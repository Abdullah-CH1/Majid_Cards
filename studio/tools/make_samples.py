def expand(entries):
    out = []
    for name, cat, desc, pb, pw, st in entries:
        s = {}
        for k, v in st.items():
            if k.startswith("kSc_") or k.startswith("kO_"):
                pre, rest = k.split("_", 1)
                s[pre + "_" + rest.replace("_", "-")] = bool(v)
            elif k == "sFs":
                s[k] = F[v]
            elif k == "sFt":
                s[k] = T[v]
            else:
                s[k] = v
        if cat in ("Signature", "Sophisticated"):
            s["kFdi"] = False
        pal = {ev: {r: PAL[key][r] for r in ROLES} for ev, key in (("baraat", pb), ("walima", pw))}
        out.append({"name": name, "cat": cat, "desc": desc, "set": s, "pal": pal})
    return out


